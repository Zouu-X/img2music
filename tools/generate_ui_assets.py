#!/usr/bin/env python3
"""Render fixed Chinese UI labels from the bundled OFL font; requires Pillow."""
from pathlib import Path
import hashlib
import struct
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
font_path = ROOT / 'assets/fonts/NotoSansCJKsc-Regular.otf'
source = font_path.read_bytes()
assert hashlib.sha256(source).hexdigest() == '2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b'
labels = [
    ('Brand', 'V2M', 22), ('Starting', '正在启动', 22),
    ('Ready', '等待拍照', 22), ('Capturing', '正在拍照', 22),
    ('Playing', '正在播放', 22), ('Done', '播放完成', 22),
    ('Stopped', '已停止', 22), ('Error', '操作失败', 22),
    ('Hint', '短按 BOOT 拍一张', 14), ('NoPhoto', '照片会显示在这里', 16),
]
# Verify every requested character against the pinned font's Unicode cmap.
tables = {}
for i in range(struct.unpack_from('>H', source, 4)[0]):
    tag, _, offset, _ = struct.unpack_from('>4sIII', source, 12 + i * 16)
    tables[tag] = offset
cmap = tables[b'cmap']
missing = {ord(c) for _, text, _ in labels for c in text if c != ' '}
for i in range(struct.unpack_from('>H', source, cmap + 2)[0]):
    platform, encoding, offset = struct.unpack_from('>HHI', source, cmap + 4 + i * 8)
    if platform != 0 and not (platform == 3 and encoding == 10):
        continue
    at = cmap + offset
    if struct.unpack_from('>H', source, at)[0] != 12:
        continue
    for group in range(struct.unpack_from('>I', source, at + 12)[0]):
        first, last, glyph = struct.unpack_from('>III', source, at + 16 + group * 12)
        missing = {cp for cp in missing if not (first <= cp <= last and glyph + cp - first != 0)}
assert not missing, f'Missing glyphs: {missing}'
header = ['// Generated by tools/generate_ui_assets.py. Font: Noto Sans CJK SC, OFL 1.1.',
          '// Font copyright and license: assets/fonts. Row-padded MSB-first 1bpp.',
          '#pragma once', '#include <stdint.h>', 'namespace ui_assets {',
          'struct TextBitmap { uint16_t width, height; const uint8_t* data; };']
preview = Image.new('RGB', (240, 360), '#111827')
total = 0
for index, (name, text, size) in enumerate(labels):
    font = ImageFont.truetype(str(font_path), size, layout_engine=ImageFont.Layout.BASIC)
    left, top, right, bottom = font.getbbox(text)
    width, height = right - left + 2, bottom - top + 2
    assert width <= 216 and height <= 30
    bitmap = Image.new('L', (width, height))
    ImageDraw.Draw(bitmap).text((1 - left, 1 - top), text, font=font, fill=255)
    packed = []
    for y in range(height):
        for x0 in range(0, width, 8):
            packed.append(sum((1 << (7 - bit)) for bit in range(8)
                              if x0 + bit < width and bitmap.getpixel((x0 + bit, y)) >= 128))
    total += len(packed)
    header.append(f'inline constexpr uint8_t k{name}Data[] = {{')
    for offset in range(0, len(packed), 20):
        header.append('  ' + ','.join(f'0x{b:02x}' for b in packed[offset:offset + 20]) + ',')
    header.extend(['};', f'inline constexpr TextBitmap k{name}{{{width}, {height}, k{name}Data}};'])
    preview.paste('#e5e7eb', ((240-width)//2, index*35+4), bitmap)
header.append('}  // namespace ui_assets\n')
(ROOT / 'firmware/v2m/ui_assets.h').write_text('\n'.join(header))
(ROOT / 'build').mkdir(exist_ok=True)
preview.save(ROOT / 'build/ui-labels-preview.png')
print(f'Generated {len(labels)} UI labels, {total} bitmap bytes.')
